// Service worker för Måltider. Sparar appens egna filer (sidor, skript, bilder) så att
// den startar snabbt och tål ett kort avbrott i nätet. Patientuppgifter finns bara i
// webbläsarens sessionStorage och går aldrig genom den här filen.
const VERSION = "maltider-v1";

self.addEventListener("install", () => self.skipWaiting());

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== VERSION).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin) return;

  // Sidor: nätet först, så att man alltid får senaste versionen. Utan nät: sparad sida.
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(VERSION).then((cache) => cache.put(request, copy));
          return response;
        })
        .catch(() => caches.match(request).then((hit) => hit || caches.match("/"))),
    );
    return;
  }

  // Skript, stilar, matbilder och ikoner ändras inte under en version: sparad fil först.
  if (/^\/(_next\/static|mat|ikoner|zxing|armband)\//.test(url.pathname)) {
    event.respondWith(
      caches.match(request).then(
        (hit) =>
          hit ||
          fetch(request).then((response) => {
            if (response.ok) {
              const copy = response.clone();
              caches.open(VERSION).then((cache) => cache.put(request, copy));
            }
            return response;
          }),
      ),
    );
  }
});
