/** Visningsnamn för data på valt språk; faller tillbaka på svenska. */
export function terminology(lang: Lang) {
  const t = lang === "sv" ? null : terms[lang];
  return {
    dish: <D extends { id: string; name: string; description: string; imageAlt: string; label?: string }>(d: D): DishText =>
      t?.dishes[d.id] ?? { name: d.name, description: d.description, imageAlt: d.imageAlt, label: d.label },
    diet: (tag: DietTag, sv: string) => t?.diet[tag] ?? sv,
    allergen: (a: string) => t?.allergens[a] ?? a,
    consistency: (c: Consistency, sv: string) => t?.consistency[c] ?? sv,
    portion: (id: Portion, sv: { name: string; hint: string }) => t?.portions[id] ?? sv,
    extra: (name: string) => t?.extras[name] ?? name,
    drink: (id: string, sv: string) => t?.drinks[id] ?? sv,
    reason: (name: string) => t?.reasons[name] ?? name,
    eaten: (id: Eaten, sv: string) => t?.eaten[id] ?? sv,
    category: (id: string, sv: string) => t?.categories[id] ?? sv,
    word: (sv: string) => t?.words[sv] ?? sv,
  };
}
